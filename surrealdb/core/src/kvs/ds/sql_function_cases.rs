//! The cases `sql_function_tests` runs: one or more per registered SQL function and dialect.
//!
//! An expectation is the text a real PostgreSQL 18 or MySQL 8 server returns for the statement,
//! except for the session and catalog functions, whose answer is the engine's own contract, and
//! the cases a comment marks as written from the documentation. `ERR:`
//! expects the statement to fail with an error that is not a missing function, and `REFUSED` that
//! the statement is refused as unsupported. A refusal is distinct from a missing function, since it
//! names a construct that the engine does not support.

/// How a case builds its statement.
pub(super) enum Sql {
	/// `SELECT <template> AS v`, with `{0}`, `{1}`... standing for the arguments. The case runs
	/// once with the arguments as literals and once with them read from the columns of a stored
	/// row.
	Call {
		template: &'static str,
		args: &'static [&'static str],
	},
	/// As `Call`, but only with the arguments as literals, for a function that reads an argument
	/// at plan time.
	Literal {
		template: &'static str,
		args: &'static [&'static str],
	},
	/// A whole statement over the fixture table `t(n, s, x)`, which holds the rows
	/// `(1, 'a', 1.5)`, `(2, 'b', 2.5)` and `(3, 'c', NULL)`. Its rows' `v` column is the result.
	Stmt(&'static str),
}

pub(super) struct Case {
	pub name: &'static str,
	pub sql: Sql,
	pub expect: &'static str,
}

impl Case {
	const fn call(
		name: &'static str,
		template: &'static str,
		args: &'static [&'static str],
		expect: &'static str,
	) -> Self {
		Self {
			name,
			sql: Sql::Call {
				template,
				args,
			},
			expect,
		}
	}

	const fn literal(
		name: &'static str,
		template: &'static str,
		args: &'static [&'static str],
		expect: &'static str,
	) -> Self {
		Self {
			name,
			sql: Sql::Literal {
				template,
				args,
			},
			expect,
		}
	}

	const fn stmt(name: &'static str, sql: &'static str, expect: &'static str) -> Self {
		Self {
			name,
			sql: Sql::Stmt(sql),
			expect,
		}
	}
}

