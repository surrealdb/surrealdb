/// The release every entry below first shipped in. An entry added by a later release names that
/// release instead, so its use raises the read floor of the catalog entries that hold it.
const FIRST: Release = Release::FIRST_STORED;

/// The kind of a parsed path.
pub enum PathKind {
	Constant(Constant),
	Function,
}

/// What the parser and the release floor know about a builtin path.
///
