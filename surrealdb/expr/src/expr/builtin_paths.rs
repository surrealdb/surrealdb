/// The entry for `path`, compared ASCII case insensitively, as the parser
/// resolves a path.
pub fn lookup(path: &str) -> Option<&'static PathKind> {
	PATHS.get(&UniCase::ascii(path)).map(|(kind, _, _)| kind)
}

/// The release `path` first shipped in, compared ASCII case insensitively, or `None` for a path
/// that is not a builtin.
pub fn release(path: &str) -> Option<Release> {
	PATHS.get(&UniCase::ascii(path)).map(|(_, _, release)| *release)
}
