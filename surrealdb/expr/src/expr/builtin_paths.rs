/// show users the exact new paths without needing string similarity to make an educated guess. The
/// third item is the release the path first shipped in. Every entry names one, so a path cannot be
/// added without declaring when it arrived.
pub type PathEntry = (PathKind, Option<UniCase<&'static str>>, Release);

