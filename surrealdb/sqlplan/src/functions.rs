//! Dialect-scoped SQL function registry and security isolation.
//!
//! Provides validation and metadata for standard SQL functions across PostgreSQL
//! and MySQL dialects, enforcing strict separation from internal SurrealQL functions
//! (`http::*`, `crypto::*`, `file::*`, `fn::*`, `sleep`, etc.).
//!
//! An entry is registered only if a statement calling it lowers and runs and answers what the
//! reference server answers, or is refused as unsupported (`0A000`) where the engine cannot run it:
//! an entry with no lowering of its own would otherwise reach the engine as a call to a function of
//! the same name, which does not exist. `kvs::ds::sql_function_tests` in `surrealdb-core` runs
//! every entry in each dialect that registers it, and fails for an entry that has no case there.
//!
//! A window function (`row_number`, `rank`, `dense_rank`, `percent_rank`, `cume_dist`, `ntile`,
//! `lag`, `lead`, `first_value`, `last_value`, `nth_value`), and `sum`, `avg`, `count`, `min` and
//! `max` called with `OVER`, lower to a `Window` operator in the select list and `ORDER BY` of a
//! `SELECT` (see `lower::window`). Any other aggregate called with `OVER`, `DISTINCT` in a window
//! call, a `GROUPS` frame, a frame `EXCLUDE` clause, a `RANGE` frame with an offset and a frame
//! offset that is not a non-negative integer literal are refused as unsupported (`0A000`).

use crate::descriptor::SqlType;
use crate::dialect::SqlDialect;

/// Classification of an SQL function.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SqlFunctionKind {
	/// Standard scalar function computed row-by-row.
	Scalar,
	/// Aggregate function computing over a grouping set, or over a window when called with
	/// `OVER`: only `sum`, `avg`, `count`, `min` and `max` lower over a window.
	Aggregate,
	/// Window function requiring an OVER clause.
	Window,
}

/// Strategy for determining return type of an SQL function.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReturnTypeStrategy {
	/// Static known SQL return type.
	Fixed(SqlType),
	/// Inherits type from the first argument.
	FirstArg,
	/// The type every argument after the first has (e.g. IF(cond, a, b)): the type they share,
	/// the widest number when they are all numbers, and unknown otherwise.
	CommonOfRest,
	/// The type every argument has (e.g. COALESCE(a, b)), as for `CommonOfRest`.
	CommonOfAll,
	/// The type of the second argument, with a `date` promoted to `timestamptz` as `date_trunc`
	/// does, and unknown for a type that is not a date or time.
	SecondArgTemporal,
	/// The element type of the range the first argument is (e.g. `lower(int4range)` is `int4`),
	/// and unknown for an argument that is not a range.
	RangeElementOfFirstArg,
	/// Numeric mathematical return type: Float8 if a float is involved, else the type of the first
	/// argument, or Int8 when there is none.
	NumericMath,
}

/// Metadata and specification for a registered SQL function.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SqlFunctionDef {
	/// Canonical function name (lowercase).
	pub name: &'static str,
	/// Function classification (Scalar, Aggregate, Window).
	pub kind: SqlFunctionKind,
	/// Minimum number of arguments required.
	pub min_args: usize,
	/// Maximum number of arguments allowed (None for variadic).
	pub max_args: Option<usize>,
	/// Return type inference strategy.
	pub return_type: ReturnTypeStrategy,
	/// Mapped internal SurrealQL function name, if applicable.
	pub internal_name: Option<&'static str>,
	/// Whether this function is valid for PostgreSQL dialect.
	pub pgsql: bool,
	/// Whether this function is valid for MySQL dialect.
	pub mysql: bool,
}

impl SqlFunctionDef {
	/// Whether the dialect registers this function.
	pub const fn is_registered_in(&self, dialect: SqlDialect) -> bool {
		match dialect {
			SqlDialect::Postgres => self.pgsql,
			SqlDialect::MySql => self.mysql,
		}
	}

	pub const fn is_aggregate(&self) -> bool {
		matches!(self.kind, SqlFunctionKind::Aggregate)
	}

	pub const fn is_window(&self) -> bool {
		matches!(self.kind, SqlFunctionKind::Window)
	}

	pub const fn is_scalar(&self) -> bool {
		matches!(self.kind, SqlFunctionKind::Scalar)
	}
}

