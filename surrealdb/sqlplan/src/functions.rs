//! Dialect-scoped SQL function registry and security isolation.
//!
//! Provides validation and metadata for standard SQL functions across PostgreSQL
//! and MySQL dialects, enforcing strict separation from internal SurrealQL functions
//! (`http::*`, `crypto::*`, `file::*`, `fn::*`, `sleep`, etc.).

use crate::descriptor::SqlType;
use crate::dialect::SqlDialect;

/// Classification of an SQL function.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SqlFunctionKind {
	/// Standard scalar function computed row-by-row.
	Scalar,
	/// Aggregate function computing over a grouping set (or usable over a window).
	Aggregate,
	/// Window function requiring an OVER clause.
	Window,
}

/// Strategy for determining return type of an SQL function.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReturnTypeStrategy {
	/// Static known SQL return type.
	Fixed(SqlType),
	/// Inherits type from the first argument.
	FirstArg,
	/// Inherits type from the second argument (e.g. IF(cond, a, b)).
	SecondArg,
	/// Numeric mathematical return type (Float8 if float involved, else Int8).
	NumericMath,
}

/// Metadata and specification for a registered SQL function.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SqlFunctionDef {
	/// Canonical function name (lowercase).
	pub name: &'static str,
	/// Function classification (Scalar, Aggregate, Window).
	pub kind: SqlFunctionKind,
	/// Minimum number of arguments required.
	pub min_args: usize,
	/// Maximum number of arguments allowed (None for variadic).
	pub max_args: Option<usize>,
	/// Return type inference strategy.
	pub return_type: ReturnTypeStrategy,
	/// Mapped internal SurrealQL function name, if applicable.
	pub internal_name: Option<&'static str>,
	/// Whether this function is valid for PostgreSQL dialect.
	pub pgsql: bool,
	/// Whether this function is valid for MySQL dialect.
	pub mysql: bool,
}

impl SqlFunctionDef {
	pub const fn is_aggregate(&self) -> bool {
		matches!(self.kind, SqlFunctionKind::Aggregate)
	}

	pub const fn is_window(&self) -> bool {
		matches!(self.kind, SqlFunctionKind::Window)
	}

	pub const fn is_scalar(&self) -> bool {
		matches!(self.kind, SqlFunctionKind::Scalar)
	}
}

