impl FunctionRegistry {
	/// Every registered function, whichever dialects accept it.
	pub fn defs() -> &'static [SqlFunctionDef] {
		FUNCTION_DEFS
	}

	/// Look up a function definition by name and dialect.
	///
	/// Automatically rejects any internal SurrealQL functions (`::` paths)
	/// or unregistered names, preventing cross-language exposure.
	pub fn lookup(name: &str, dialect: SqlDialect) -> Option<&'static SqlFunctionDef> {
		if name.contains("::") {
			return None;
		}

		let lower = name.to_ascii_lowercase();
		FUNCTION_DEFS.iter().find(|def| {
			if def.name != lower {
				return false;
			}
			match dialect {
				SqlDialect::Postgres => def.pgsql,
				SqlDialect::MySql => def.mysql,
			}
		})
	}

	/// Check whether a function is registered as an aggregate for the dialect.
	pub fn is_aggregate(name: &str, dialect: SqlDialect) -> bool {
		Self::lookup(name, dialect).map(|d| d.is_aggregate()).unwrap_or(false)
	}

	/// Check whether `name` is an aggregate of either dialect. A bound call has already been
	/// resolved under its own dialect, so a name that is an aggregate of the other one only
	/// is never reached.
	pub fn is_bound_aggregate(name: &str) -> bool {
		Self::is_aggregate(name, SqlDialect::Postgres)
			|| Self::is_aggregate(name, SqlDialect::MySql)
	}

	/// Check whether a function is registered as a window function for the dialect.
	pub fn is_window(name: &str, dialect: SqlDialect) -> bool {
		Self::lookup(name, dialect).map(|d| d.is_window()).unwrap_or(false)
	}

	/// Check whether a function is registered as a scalar function for the dialect.
	pub fn is_scalar(name: &str, dialect: SqlDialect) -> bool {
		Self::lookup(name, dialect).map(|d| d.is_scalar()).unwrap_or(false)
	}

	/// Infer the return type for a function call.
	pub fn infer_return_type(name: &str, dialect: SqlDialect, arg_types: &[SqlType]) -> SqlType {
		let arg_types: Vec<Option<SqlType>> = arg_types.iter().copied().map(Some).collect();
		Self::infer_return_type_of_call(name, dialect, &arg_types)
	}

	/// Infer return type across dialects.
	pub fn infer_return_type_any(name: &str, arg_types: &[SqlType]) -> SqlType {
		let arg_types: Vec<Option<SqlType>> = arg_types.iter().copied().map(Some).collect();
		Self::infer_return_type_of_arguments(name, &arg_types)
	}

	/// Infer return type across dialects for a call whose argument is the literal `NULL` where
	/// `arg_types` holds `None`. A `NULL` argument has no value of its own, so it takes no part in
	/// the type its alternatives share.
	pub fn infer_return_type_of_arguments(name: &str, arg_types: &[Option<SqlType>]) -> SqlType {
		let ty = Self::infer_return_type_of_call(name, SqlDialect::Postgres, arg_types);
		if ty != SqlType::Unknown {
			ty
		} else {
			Self::infer_return_type_of_call(name, SqlDialect::MySql, arg_types)
		}
	}

	/// The return type of a call under `dialect`, where an argument of the literal `NULL` is
	/// `None`.
	pub(crate) fn infer_return_type_of_call_in(
		name: &str,
		dialect: SqlDialect,
		arg_types: &[Option<SqlType>],
	) -> SqlType {
		Self::infer_return_type_of_call(name, dialect, arg_types)
	}

	fn infer_return_type_of_call(
		name: &str,
		dialect: SqlDialect,
		arg_types: &[Option<SqlType>],
	) -> SqlType {
		let Some(def) = Self::lookup(name, dialect) else {
			return SqlType::Unknown;
		};

		match def.return_type {
			ReturnTypeStrategy::Fixed(t) => t,
			// A sum of `smallint` and `integer` values is a `bigint`, which holds a sum the
			// narrower type cannot: PostgreSQL adds them as `bigint`, and MySQL sums integers
			// wider than any column holds them.
			ReturnTypeStrategy::FirstArg if def.name == "sum" => {
				match arg_types.first().copied().flatten() {
					Some(SqlType::Int2 | SqlType::Int4) => SqlType::Int8,
					Some(other) => other,
					None => SqlType::Unknown,
				}
			}
			ReturnTypeStrategy::FirstArg => {
				arg_types.first().copied().flatten().unwrap_or(SqlType::Unknown)
			}
			ReturnTypeStrategy::RangeElementOfFirstArg => {
				if let Some(Some(SqlType::Range(element))) = arg_types.first() {
					SqlType::of_range_element(*element)
				} else {
					SqlType::Unknown
				}
			}
			ReturnTypeStrategy::SecondArgTemporal => match arg_types.get(1).copied().flatten() {
				Some(SqlType::Date) => SqlType::TimestampTz,
				Some(
					ty @ (SqlType::Time
					| SqlType::Timestamp
					| SqlType::TimestampTz
					| SqlType::Interval),
				) => ty,
				_ => SqlType::Unknown,
			},
			ReturnTypeStrategy::CommonOfRest => {
				SqlType::common(arg_types.iter().skip(1).flatten().copied())
			}
			ReturnTypeStrategy::CommonOfAll => SqlType::common(arg_types.iter().flatten().copied()),
			ReturnTypeStrategy::NumericMath => {
				if arg_types
					.iter()
					.flatten()
					.any(|t| matches!(t, SqlType::Float4 | SqlType::Float8))
				{
					SqlType::Float8
				} else if let Some(first) = arg_types.first() {
					first.unwrap_or(SqlType::Unknown)
				} else {
					SqlType::Int8
				}
			}
		}
	}
}
