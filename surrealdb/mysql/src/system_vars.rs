/// The system variable `name` with its value, or `None` when the server does not model it. The
/// variable can still be one MySQL has ([`mysql_system_variable_scope`]), which reads as NULL.
pub fn mysql_system_variable(name: &str) -> Option<SystemVariable> {
	VARIABLES
		.iter()
		.find(|(known, _)| known.eq_ignore_ascii_case(name))
		.map(|(_, variable)| *variable)
}

/// Every variable the server models with its value, in ascending order of name. The names are
/// lower case and none is listed twice.
pub fn mysql_system_variables() -> &'static [(&'static str, SystemVariable)] {
	VARIABLES
}

/// The name of the variable `name` as MySQL spells it and the scopes it can be read in, or `None`
/// when MySQL has no such variable.
fn find_variable(name: &str) -> Option<(&'static str, VariableScope)> {
	NAMES
		.binary_search_by(|(known, _)| {
			known.bytes().cmp(name.bytes().map(|byte| byte.to_ascii_lowercase()))
		})
		.ok()
		.and_then(|at| NAMES.get(at).copied())
}

/// The scopes the variable `name` can be read in, or `None` when MySQL has no such variable.
pub fn mysql_system_variable_scope(name: &str) -> Option<VariableScope> {
	find_variable(name).map(|(_, scope)| scope)
}

/// Every variable MySQL has with the scopes it can be read in, in ascending order of name. The
/// names are lower case and none is listed twice.
pub fn mysql_system_variable_names() -> &'static [(&'static str, VariableScope)] {
	NAMES
}

/// Whether MySQL accepts a read of `@@name`, or `@@global.name` when `global` is set. MySQL
/// refuses a name it has no variable of and `@@global.name` of a variable only a session has.
///
/// A reference with `session.` or `local.` is not told from one without a scope, and a variable
/// that only the server has reads the same through either, so the refusal MySQL gives for
/// `@@session.name` of such a variable is not given.
pub fn check_mysql_system_variable(name: &str, global: bool) -> Result<(), SystemVariableError> {
	match find_variable(name) {
		None => Err(SystemVariableError::unknown(name)),
		Some((known, Session)) if global => Err(SystemVariableError::SessionOnly(known.to_owned())),
		Some((_, Global | Session | Both)) => Ok(()),
	}
}

