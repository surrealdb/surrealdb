//! The MySQL system variables of the server: the names it accepts and the fixed values it answers.
//!
//! A name is matched without regard to case, and two tables describe it.
//!
//! * The names MySQL has ([`mysql_system_variable_scope`]): every variable that `SHOW VARIABLES`
//!   lists on MySQL 8.4, and those that MySQL 8.0.35 lists and 8.4 no longer has, because the
//!   server announces an 8.0 version. The list holds the variables of a server with no plugin or
//!   component installed. A reference to a name outside the list is refused as MySQL refuses it
//!   ([`SystemVariableError`]), and every name inside the list is answered.
//! * The values of the variables the server models ([`mysql_system_variable`]). A variable is a
//!   number, answered as a 64-bit integer, or a text, and a result column that holds it has the
//!   type of its value. The table holds the server's own settings, so a `SET` of a variable does
//!   not change what it holds, and it holds nothing about the host the server runs on, such as a
//!   path, the host name, the port or the operating system. A name MySQL has and the table does not
//!   model reads as NULL.

use VariableScope::{Both, Global, Session};
use thiserror::Error;

/// The version the server announces: in the handshake of the MySQL wire protocol, to
/// `SELECT VERSION()` and as the variable `version`.
pub const MYSQL_SERVER_VERSION: &str = "8.0.35-SurrealDB";

/// The collation of the server, the connection and every database, and the default collation of
/// the `utf8mb4` character set.
pub const MYSQL_DEFAULT_COLLATION: &str = "utf8mb4_0900_ai_ci";

/// The longest name, in bytes, that an error about an unknown variable repeats.
const MAX_ERROR_NAME_BYTES: usize = 64;

/// The value of a system variable, which is also the type of its result column.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SystemVariable {
	/// A numeric variable, answered as a 64-bit integer.
	Int(i64),
	/// A switch. `SELECT @@name` answers it as the integer 1 or 0, as MySQL does, and
	/// `SHOW VARIABLES` lists it as `ON` or `OFF`.
	Flag(bool),
	/// A text variable.
	Text(&'static str),
}

impl SystemVariable {
	/// The value as `SHOW VARIABLES` lists it.
	pub fn listed(self) -> String {
		match self {
			Self::Int(number) => number.to_string(),
			Self::Flag(true) => "ON".to_owned(),
			Self::Flag(false) => "OFF".to_owned(),
			Self::Text(text) => text.to_owned(),
		}
	}
}

/// The scopes a system variable can be read in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VariableScope {
	/// The variable belongs to the server, so `@@global.name` and `@@name` read it.
	Global,
	/// The variable belongs to a session, so `@@session.name` and `@@name` read it, and
	/// `@@global.name` is an error.
	Session,
	/// The variable has a global and a session value.
	Both,
}

/// Why MySQL does not accept a reference to a system variable.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum SystemVariableError {
	/// MySQL has no variable of this name. The name is cut to [`MAX_ERROR_NAME_BYTES`] bytes, at
	/// a character boundary.
	#[error("Unknown system variable '{0}'")]
	Unknown(String),
	/// `@@global.name` of a variable that only a session has. The name is the variable's own.
	#[error("Variable '{0}' is a SESSION variable")]
	SessionOnly(String),
}

impl SystemVariableError {
	/// The MySQL error number: `ER_UNKNOWN_SYSTEM_VARIABLE` for an unknown name and
	/// `ER_INCORRECT_GLOBAL_LOCAL_VAR` for a scope the variable does not have.
	pub const fn mysql_error_code(&self) -> u16 {
		match self {
			Self::Unknown(_) => 1193,
			Self::SessionOnly(_) => 1238,
		}
	}

	fn unknown(name: &str) -> Self {
		Self::Unknown(name[..name.floor_char_boundary(MAX_ERROR_NAME_BYTES)].to_owned())
	}
}

